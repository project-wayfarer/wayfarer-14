using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Library.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Player;
using System.Linq; // Wayfarer

namespace Content.Client._NF.Library.UI;

[GenerateTypedNameReferences]
public sealed partial class LibraryConsoleMenu : FancyWindow
{
    [Dependency] protected readonly ISharedPlayerManager Player = default!; // Wayfarer

    public event Action<string, string, string, string, bool, bool>? UploadBookRequested; // Wayfarer
    public event Action<int>? DownloadBookRequested;
    public event Action<int, string>? ReUploadBookRequested; // Wayfarer
    public event Action<int>? DeleteBookRequested; // Wayfarer

    private bool _powered;
    private bool _hasBook;
    private string _bookContent = string.Empty;
    private int _selectedBookIndex = -1;
    private readonly List<int> _bookIds = new();
    private readonly List<LibraryBookData> _allBooks = new();
    private int _sortMode = 0; // Wayfarer

    public LibraryConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);  // Wayfarer

        MainTabContainer.SetTabTitle(0, Loc.GetString("library-console-tab-upload"));
        MainTabContainer.SetTabTitle(1, Loc.GetString("library-console-tab-browse"));
        // Wayfarer
        SortOrder.AddItem(Loc.GetString("library-console-browse-newest"));
        SortOrder.AddItem(Loc.GetString("library-console-browse-oldest"));
        SortOrder.AddItem(Loc.GetString("library-console-browse-name"));
        SortOrder.OnItemSelected += ChangeSort;
        // End Wayfarer
        UploadBookButton.OnPressed += _ =>
            UploadBookRequested?.Invoke(TitleEdit.Text, AuthorEdit.Text, _bookContent, WarningEdit.Text, IsNSFW.Pressed, IsPublishable.Pressed); // Wayfarer
        DownloadBookButton.OnPressed += _ =>
        {
            if (_selectedBookIndex < 0 || _selectedBookIndex >= _bookIds.Count)
                return;
            DownloadBookRequested?.Invoke(_bookIds[_selectedBookIndex]);
        };

        // Wayfarer
        ReUploadBookButton.OnPressed += _ =>
        {
            ReUploadBookButton.Visible = false;
            ReUploadBookButtonConf.Visible = true;
        };

        ReUploadBookButtonConf.OnPressed += _ =>
        {
            if (_selectedBookIndex < 0 || _selectedBookIndex >= _bookIds.Count || !_hasBook)
                return;
            ReUploadBookRequested?.Invoke(_bookIds[_selectedBookIndex], _bookContent);
        };

        DeleteBookButton.OnPressed += _ =>
        {
            DeleteBookButton.Visible = false;
            DeleteBookButtonConf.Visible = true;
        };

        DeleteBookButtonConf.OnPressed += _ =>
        {
            if (_selectedBookIndex < 0 || _selectedBookIndex >= _bookIds.Count)
                return;
            DeleteBookRequested?.Invoke(_bookIds[_selectedBookIndex]);
        };
        // End Wayfarer

        BookList.OnItemSelected += args =>
        {
            _selectedBookIndex = args.ItemIndex;
            // Wayfarer
            var id = _bookIds[_selectedBookIndex];
            var book = _allBooks.FirstOrDefault(x => x.Id == id);
            if (book == null)
            {
                ContentWarnings.Text = "";
            }
            else if (string.IsNullOrWhiteSpace(book.Warnings))
            {
                ContentWarnings.Text = Loc.GetString("library-console-browse-warnings-empty");
            }
            else
            {
                ContentWarnings.Text = Loc.GetString("library-book-warnings", ("warnings", book.Warnings));
            }

            UpdateDownloadButtonState(book);
            // End Wayfarer
            // UpdateDownloadButtonState();
        };
        BookList.OnItemDeselected += _ =>
        {
            _selectedBookIndex = -1;
            ContentWarnings.Text = ""; // Wayfarer
            UpdateDownloadButtonState();
        };

        ShowNSFW.OnPressed += _ => FilterBookList(); // Wayfarer
        ShowMine.OnPressed += _ => FilterBookList(); // Wayfarer
        SearchEdit.OnTextChanged += _ => FilterBookList();
    }

    // Wayfarer
    private void ChangeSort(OptionButton.ItemSelectedEventArgs args)
    {
        _sortMode = args.Id;
        SortOrder.Select(_sortMode);
        FilterBookList();
    }
    // End Wayfarer
    public void SetEnabled(bool enabled)
    {
        _powered = enabled;
        TitleEdit.Editable = enabled;
        AuthorEdit.Editable = enabled;
        UpdateUploadButtonState();
        UpdateDownloadButtonState();
    }

    /// <summary>
    /// Updates the content field from the inserted book. Pass null when no book is inserted.
    /// </summary>
    public void SetBookContent(bool powered, string? content)
    {
        _powered = powered;
        _hasBook = content != null;
        _bookContent = content ?? string.Empty;
        UpdateUploadButtonState();
        UpdateDownloadButtonState();
    }

    /// <summary>
    /// Populates the browse tab list with library books.
    /// </summary>
    public void PopulateBookList(List<LibraryBookData>? books)
    {
        _allBooks.Clear();
        if (books != null)
            _allBooks.AddRange(books);
        FilterBookList();
    }

    /// <summary>
    /// Rebuilds the visible book list, filtering by the current search text against title and author.
    /// </summary>
    private void FilterBookList()
    {
        BookList.Clear();
        _bookIds.Clear();
        _selectedBookIndex = -1;

        var query = SearchEdit.Text.Trim();

        var filtered = string.IsNullOrEmpty(query)
            ? _allBooks
            : _allBooks.FindAll(b =>
                b.Title.Contains(query, System.StringComparison.OrdinalIgnoreCase) ||
                b.Author.Contains(query, System.StringComparison.OrdinalIgnoreCase));
        // Wayfarer
        if (!ShowNSFW.Pressed)
        {
            filtered = filtered.Where(x => !x.IsNSFW).ToList();
        }

        if (ShowMine.Pressed)
        {
            filtered = filtered.Where(x => x.AuthorId == Player.LocalSession?.UserId.UserId).ToList();
        }

        switch (_sortMode)
        {
            case 0:
                filtered = filtered.OrderByDescending(x => x.Date).ToList();
                break;
            case 1:
                filtered = filtered.OrderBy(x => x.Date).ToList();
                break;
            case 2:
                filtered = filtered.OrderBy(x => x.Title).ToList();
                break;
        }
        // End Wayfarer
        if (filtered.Count == 0)
        {
            BrowseEmptyLabel.Visible = true;
            UpdateDownloadButtonState();
            return;
        }

        BrowseEmptyLabel.Visible = false;
        foreach (var book in filtered)
        {
            BookList.AddItem($"{(book.IsNSFW ? Loc.GetString("library-console-download-nsfw-header") + " " : "")}{book.Title}  —  {book.Author}"); // Wayfarer
            _bookIds.Add(book.Id);
        }
        UpdateDownloadButtonState();
    }

    private void UpdateUploadButtonState()
    {
        UploadBookButton.Disabled = !_powered || !_hasBook;
        UploadBookButton.Text = Loc.GetString(_hasBook ? "library-console-upload-book-button" : "library-console-upload-placeholder"); // Wayfarer
    }

    private void UpdateDownloadButtonState(LibraryBookData? book = null) // Wayfarer
    {
        DownloadBookButton.Disabled = !_powered || !_hasBook || _selectedBookIndex < 0;
        // Wayfarer
        ReUploadBookButton.Disabled = !_powered || !_hasBook || _selectedBookIndex < 0;
        if (book != null && book.AuthorId != null && book.AuthorId == Player.LocalSession?.UserId.UserId)
        {
            ReUploadBookButton.Visible = true;
            DeleteBookButton.Visible = true;
        }
        else
        {
            ReUploadBookButton.Visible = false;
            DeleteBookButton.Visible = false;
        }
        ReUploadBookButtonConf.Visible = false;
        DeleteBookButtonConf.Visible = false;
        // End Wayfarer
    }
}
